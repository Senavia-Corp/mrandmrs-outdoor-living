#!/usr/bin/env node
/**
 * INVENTARIO DEL BLOG — los 47 articulos con su intencion, su pagina de dinero y sus enlaces
 * (SEO-REMEDIACION, 4-oct-2026).   node scripts/build-blog-inventory.mjs -> seo-audit/blog-inventory.md
 *
 * Fuentes: `src/data/blogs-sanity.json` (la cache versionada de Sanity), el inventario de URLs
 * (`seo-audit/url-inventory.json`, enlaces de cuerpo) y `seo-intent-registry.json`. La
 * disposicion sale de reglas escritas aqui: ningun articulo se fusiona ni se redirige sin datos de
 * Search Console por URL, que esta sesion no tiene.
 */
import fs from 'node:fs';
import path from 'node:path';

const RAIZ = path.resolve(import.meta.dirname, '..');
const lee = (p) => JSON.parse(fs.readFileSync(path.join(RAIZ, p), 'utf8'));
const POSTS = lee('src/data/blogs-sanity.json');
const INV = new Map(lee('seo-audit/url-inventory.json').filas.map((f) => [f.ruta, f]));
const INT = lee('src/data/seo-intent-registry.json').intenciones;
const REESCRITOS = new Set(Object.keys(lee('src/data/blog-reescritos.json').rutas ?? {}));

const DINERO = [
  [/remodel|renovat|resurfac|rebuild|old-pool/, '/services/pool-remodeling'],
  [/louver/, '/services/louvered-roofs'],
  [/pergola/, '/services/pergola-builders'],
  [/kitchen|grill/, '/services/outdoor-kitchens'],
  [/screen|enclosure|lanai/, '/services/pool-screen-enclosures'],
  [/deck/, '/services/deck-builders'],
  [/landscap|irrigat/, '/services/landscaping'],
  [/commercial|multifamily|hospitality/, '/industry-solutions'],
  [/pool|spa|plunge|finish/, '/services/pool-builders'],
];
const dinero = (slug) => DINERO.find(([re]) => re.test(slug))?.[1] ?? '/services/pool-builders';
const CORE = new Set(['/services/pool-builders', '/services/pool-remodeling']);

const filas = POSTS.map((p) => {
  const ruta = `/blogs/${p.slug}`;
  const inv = INV.get(ruta);
  const md = dinero(p.slug);
  const enlazaDinero = inv?.enlacesSalientes?.includes(md) ?? false;
  const intent = INT.find((i) => i.duena === ruta || (i.apoyo ?? []).includes(ruta));
  const disp = !enlazaDinero ? 'UPDATE (add contextual link to money page)'
    : REESCRITOS.has(ruta) ? 'KEEP (rewritten 1-Oct-2026)' : 'KEEP';
  return { ruta, titulo: p.title, cat: p.categoria?.name ?? '', md, core: CORE.has(md), enlazaDinero,
    entrantes: inv?.enlacesEntrantes ?? 0, faq: (p.faq ?? []).length, fuentes: (p.fuentes ?? []).length,
    intent: intent?.id ?? '', disp };
});

const core = filas.filter((f) => f.core);
const md = `# Blog Inventory — ${filas.length} articles

Generated by \`node scripts/build-blog-inventory.mjs\` on ${new Date().toISOString().slice(0, 10)} from the versioned Sanity cache,
the URL inventory (body links only) and the intent registry. **No article was created, merged or
redirected in this remediation**: the intent lock of 1-Oct-2026 (\`seo-intent-registry.json\`) already
separates overlapping topics (cost vs. timeline vs. permits; new-build vs. remodel) and each URL has
its own impressions. Merging without per-URL Search Console data would risk existing equity.

- Articles supporting the two core money pages (custom pool construction, complete remodeling): **${core.length}**
- Articles whose body links to their money page: **${filas.filter((f) => f.enlazaDinero).length}/${filas.length}**
- Articles with a FAQ block: **${filas.filter((f) => f.faq).length}** · with cited sources: **${filas.filter((f) => f.fuentes).length}**
- Priority topics the brief lists (cost, permits, timeline, builder selection, questions before hiring, process, design, pool + spa, complete remodel, remodel vs rebuild, renovation investment) are **all already covered** by an existing article — see the table; none needs a new URL.

| Article | Category | Money page it supports | Links to it | Inbound (body) | FAQ | Sources | Intent | Disposition |
|---|---|---|---|---|---|---|---|---|
${filas.sort((a, b) => Number(b.core) - Number(a.core) || a.md.localeCompare(b.md)).map((f) => `| \`${f.ruta.replace('/blogs/', '')}\` | ${f.cat} | \`${f.md}\` | ${f.enlazaDinero ? 'yes' : '**no**'} | ${f.entrantes} | ${f.faq} | ${f.fuentes} | ${f.intent} | ${f.disp} |`).join('\n')}
`;
fs.writeFileSync(path.join(RAIZ, 'seo-audit/blog-inventory.md'), md);
console.log(`blog: ${filas.length} articulos · ${core.length} de nucleo · ${filas.filter((f) => !f.enlazaDinero).length} sin enlace a su pagina de dinero`);
